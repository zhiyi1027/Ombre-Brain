"""Shared factual-boundary rules for memory-processing prompts."""

from __future__ import annotations


def relationship_semantics_rule(human: str = "人类一方") -> str:
    """Keep affectionate forms of address from becoming invented kinship facts."""

    return f"""

【称呼与真实关系消歧——事实边界】
关系类元数据属于事实判断，不能靠称呼的字面或语义联想补全：
- 「爸爸/爸比/爹地/daddy」「妈妈/mommy」「哥哥/姐姐」「女儿/儿子」等词出现在呼语、昵称、调情、
  权力互动或角色扮演中时，只能证明一种称呼方式，不能证明血缘、收养、监护、年龄或现实亲属身份。
- 先看全文明确陈述的关系和互动语境。若「{human}」是在称呼「我」（AI），且上下文出现恋人、夫妻、
  老公/老婆、亲吻、调情、性或亲密互动，应按伴侣昵称或角色互动理解；不得据此生成「亲子」「父女」
  「父子」「血缘」「养父/养女」「未成年人」等事实性关系。
- 只有原文明示现实亲属关系（如「我的父亲」「她的亲生女儿」「从小由养父抚养」），或明确说明作品中
  人物确有该设定时，才允许生成对应的亲属关系描述。
- 不得仅因亲属式称呼选择「家庭」主题域。关系不明确时保留字面事实，例如「爸爸称呼」「亲昵称呼」；
  不猜测关系身份。
- domain 描述正文的主事件，不描述说话双方的固定关系。即使双方是伴侣，正文主要在修代码、看病、吃饭、
  购物时，也应优先选择「编程」「健康」「饮食」「购物」等实际主题；不能只因出现老公/老婆、爸爸/宝宝、
  爱你等称呼就附加关系域。
- 只有正文重点在关系本身（承诺、争吵和好、吃醋、信任、相处变化）时选「伴侣」；非性的拥抱、亲吻、
  撒娇和哄人选「亲密」；明确的性欲、性行为或性偏好选「性」。最多选择真正居于中心的 1~2 个域。
- 本规则同时约束正文、摘要、标题、domain、tags、keywords；语义扩展不得引入与原文关系证据冲突的词。

判例：
- 「爸爸亲亲，我是你老婆」→ 伴侣、亲密、亲昵称呼；不是父女或亲子。
- 「我父亲今天陪我去医院」→ 可以标记家庭、父亲或亲子关系。
"""
